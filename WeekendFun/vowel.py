letter = input("Enter a Letter of the Alphabet: ")
if letter == "a" or letter == "e" or letter == "i" or letter == "o" or letter == "u": 
    print("Vowel")
elif letter != "a" and letter != "e" and letter != "i" and letter != "o" and letter != "u": 
    print("Consonant")   
else:        
    print("Invalid Input")         
